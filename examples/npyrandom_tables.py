#!/usr/bin/env python3
"""Write native/npyrandom.h: numpy's ziggurat tables for its standard normal.

    python3 examples/npyrandom_tables.py

The organ's wind (wind.py) draws its wander from numpy's
default_rng(seed).standard_normal -- PCG64 and numpy's ziggurat -- and the
native engine must draw the same numbers (native/npyrandom.c). The three
256-entry tables (ki, wi, fi) are numpy's own, read out of the installed
numpy's static library (numpy/random/lib/libnpyrandom.a: the
distributions object's .rodata) rather than recomputed, so they are its
bits. Rerun it if numpy changes.
"""
import os
import re
import struct
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def main():
    import numpy as np
    lib = os.path.join(os.path.dirname(np.__file__), 'random', 'lib', 'libnpyrandom.a')
    with tempfile.TemporaryDirectory() as tmp:
        names = subprocess.check_output(['ar', 't', lib], text=True).split()
        member = next(n for n in names if n.endswith('distributions.c.o') and 'distributions_distributions' in n)
        subprocess.check_call(['ar', 'x', lib, member], cwd=tmp)
        obj = os.path.join(tmp, member)
        secs = subprocess.check_output(['readelf', '-S', '-W', obj], text=True)
        m = re.search(r'\]\s+\.rodata\s+PROGBITS\s+[0-9a-f]+\s+([0-9a-f]+)', secs)
        base = int(m.group(1), 16)
        syms = subprocess.check_output(['objdump', '-t', obj], text=True)
        data = open(obj, 'rb').read()
        tabs = {}
        for name, fmt in (('ki_double', '<256Q'), ('wi_double', '<256d'), ('fi_double', '<256d')):
            m = re.search(r'^([0-9a-f]+)\s+l\s+O\s+\.rodata\s+([0-9a-f]+)\s+' + name + r'$', syms, re.M)
            off, size = int(m.group(1), 16), int(m.group(2), 16)
            assert size == 2048
            tabs[name] = struct.unpack(fmt, data[base + off:base + off + size])
    out = ['/* npyrandom.h -- GENERATED by examples/npyrandom_tables.py from numpy %s\'s', ' * libnpyrandom.a:'
           ' its ziggurat tables for random_standard_normal. Do not edit. */', '']
    out[0] = out[0] % np.__version__
    out.append('static const uint64_t NPY_KI[256] = {')
    out += ['    %s,' % ', '.join('0x%016xULL' % v for v in tabs['ki_double'][i:i + 4]) for i in range(0, 256, 4)]
    out.append('};')
    for name, cname in (('wi_double', 'NPY_WI'), ('fi_double', 'NPY_FI')):
        out.append('static const double %s[256] = {' % cname)
        out += ['    %s,' % ', '.join(float(v).hex() for v in tabs[name][i:i + 4]) for i in range(0, 256, 4)]
        out.append('};')
    path = os.path.join(HERE, 'native', 'npyrandom.h')
    with open(path, 'w') as f:
        f.write('\n'.join(out) + '\n')
    print('wrote', path)
    return 0


if __name__ == '__main__':
    sys.exit(main())
